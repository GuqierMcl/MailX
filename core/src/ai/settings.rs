//! The `ai` section of the settings file. Only the AI commands change it
//! (`SettingsStore::update_ai`); the general settings patch does not accept it.
//! Secrets never live here.

use std::collections::HashSet;

use serde::{Deserialize, Serialize};
use ts_rs::TS;
use uuid::Uuid;

use super::validation::{
    CUSTOM_PROVIDER_ID, MAX_CONNECTIONS, clean_model_name, normalize_base_url, normalize_name,
    valid_model_id, valid_provider_id,
};
use crate::{AppError, settings::ServiceRoute};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub enum AiProtocol {
    /// `/models` and `/chat/completions` with a Bearer key.
    OpenaiCompatible,
    /// `/models` and `/messages` with `x-api-key`.
    Anthropic,
}

/// One provider, one key, one address. The same provider may be connected
/// several times.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct AiConnection {
    /// Generated by the core.
    pub id: String,
    /// A catalog id, or `custom`.
    pub provider_id: String,
    pub name: String,
    pub protocol: AiProtocol,
    /// Normalized: no trailing `/`; the version segment is part of it.
    pub base_url: String,
    /// Goes through the AI proxy when one is set; otherwise connects directly.
    pub use_proxy: bool,
}

/// A model of one connection, as it looked when it was chosen.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct AiModelRef {
    pub connection_id: String,
    pub model_id: String,
    pub name: String,
    pub context_length: Option<u32>,
    pub output_length: Option<u32>,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase", default)]
pub struct AiSettings {
    pub connections: Vec<AiConnection>,
    pub default_model: Option<AiModelRef>,
    /// The model that translates mail; `None` follows `default_model`.
    pub translation_model: Option<AiModelRef>,
    /// The AI proxy, shared by every connection that uses it and by the
    /// catalog and icon downloads.
    pub route: ServiceRoute,
}

impl AiConnection {
    /// Checks and canonicalizes the fields; `None` for a connection that cannot be kept.
    pub(crate) fn normalized(self) -> Option<Self> {
        Uuid::parse_str(&self.id).ok()?;
        Some(Self {
            provider_id: if valid_provider_id(&self.provider_id) {
                self.provider_id
            } else {
                CUSTOM_PROVIDER_ID.to_owned()
            },
            name: normalize_name(&self.name)?,
            base_url: normalize_base_url(&self.base_url)?,
            ..self
        })
    }
}

impl AiModelRef {
    pub(crate) fn normalized(self) -> Option<Self> {
        let name = clean_model_name(&self.name).unwrap_or_else(|| self.model_id.clone());
        valid_model_id(&self.model_id).then_some(Self { name, ..self })
    }
}

impl AiSettings {
    /// Validates client input. Errors name the offending field.
    pub(crate) fn normalized(self) -> Result<Self, AppError> {
        if self.connections.len() > MAX_CONNECTIONS {
            return Err(AppError::validation("ai.connections"));
        }
        self.route.validate("ai.route")?;
        let mut ids = HashSet::new();
        let mut connections = Vec::with_capacity(self.connections.len());
        for connection in self.connections {
            let connection = connection
                .normalized()
                .ok_or_else(|| AppError::validation("ai.connections"))?;
            if !ids.insert(connection.id.clone()) {
                return Err(AppError::validation("ai.connections"));
            }
            connections.push(connection);
        }
        let checked = |model: Option<AiModelRef>, field: &str| match model {
            Some(model) => {
                let model = model
                    .normalized()
                    .ok_or_else(|| AppError::validation(field))?;
                if !ids.contains(&model.connection_id) {
                    return Err(AppError::validation(field));
                }
                Ok(Some(model))
            }
            None => Ok(None),
        };
        let default_model = checked(self.default_model, "ai.defaultModel")?;
        let translation_model = checked(self.translation_model, "ai.translationModel")?;
        Ok(Self {
            connections,
            default_model,
            translation_model,
            route: self.route,
        })
    }

    /// For stored files: drops what cannot be used instead of failing, and
    /// clears a default model whose connection is gone.
    pub(crate) fn sanitized(self) -> Self {
        let mut ids = HashSet::new();
        let connections: Vec<AiConnection> = self
            .connections
            .into_iter()
            .filter_map(AiConnection::normalized)
            .filter(|connection| ids.insert(connection.id.clone()))
            .take(MAX_CONNECTIONS)
            .collect();
        let usable = |model: Option<AiModelRef>| {
            model
                .and_then(AiModelRef::normalized)
                .filter(|model| connections.iter().any(|c| c.id == model.connection_id))
        };
        let default_model = usable(self.default_model);
        let translation_model = usable(self.translation_model);
        Self {
            connections,
            default_model,
            translation_model,
            route: self.route.sanitized(),
        }
    }
}

/// Drops `ai` fields of the wrong type, and connections that do not parse, so
/// a hand-edited file loses only the broken part instead of the whole file.
pub(crate) fn repair_ai(value: &mut serde_json::Value) {
    let Some(section) = value.as_object_mut() else {
        return;
    };
    if let Some(route) = section.get_mut("route").and_then(|v| v.as_object_mut())
        && route.get("username").is_some_and(|v| !v.is_string())
    {
        route.remove("username");
    }
    section.retain(|key, v| match key.as_str() {
        "connections" => v.is_array(),
        "defaultModel" | "translationModel" => {
            v.is_null() || serde_json::from_value::<AiModelRef>(v.clone()).is_ok()
        }
        "route" => serde_json::from_value::<ServiceRoute>(v.clone()).is_ok(),
        _ => true,
    });
    if let Some(connections) = section
        .get_mut("connections")
        .and_then(|v| v.as_array_mut())
    {
        connections.retain(|v| serde_json::from_value::<AiConnection>(v.clone()).is_ok());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn connection(id: &str, name: &str, url: &str) -> AiConnection {
        AiConnection {
            id: id.into(),
            provider_id: "openai".into(),
            name: name.into(),
            protocol: AiProtocol::OpenaiCompatible,
            base_url: url.into(),
            use_proxy: false,
        }
    }

    fn id() -> String {
        Uuid::new_v4().to_string()
    }

    #[test]
    fn sanitizing_drops_bad_connections_and_dangling_defaults() {
        let good = connection(&id(), " Mine ", "https://api.openai.com/v1/");
        let gone = connection(&id(), "Gone", "https://example.com/v1");
        let settings = AiSettings {
            connections: vec![
                good.clone(),
                connection("not-a-uuid", "Bad id", "https://example.com/v1"),
                connection(&id(), "  ", "https://example.com/v1"),
                connection(&id(), "Bad url", "ftp://example.com"),
                good.clone(),
            ],
            default_model: Some(AiModelRef {
                connection_id: gone.id.clone(),
                model_id: "m".into(),
                name: "M".into(),
                context_length: None,
                output_length: None,
            }),
            translation_model: None,
            route: ServiceRoute::Proxy {
                proxy_kind: crate::accounts::types::ProxyKind::Socks5,
                host: String::new(),
                port: 1080,
                username: String::new(),
            },
        };
        let sanitized = settings.sanitized();
        assert_eq!(sanitized.connections.len(), 1);
        assert_eq!(sanitized.connections[0].name, "Mine");
        assert_eq!(
            sanitized.connections[0].base_url,
            "https://api.openai.com/v1"
        );
        assert_eq!(sanitized.default_model, None);
        assert_eq!(sanitized.route, ServiceRoute::Direct);
    }

    #[test]
    fn normalizing_rejects_bad_input_with_the_field_name() {
        let ok = connection(&id(), "A", "https://example.com/v1");
        let settings = |connections: Vec<AiConnection>| AiSettings {
            connections,
            ..AiSettings::default()
        };
        assert!(settings(vec![ok.clone()]).normalized().is_ok());
        assert_eq!(
            settings(vec![ok.clone(), ok.clone()])
                .normalized()
                .unwrap_err()
                .field
                .as_deref(),
            Some("ai.connections")
        );
        let many = (0..21)
            .map(|i| connection(&id(), &format!("c{i}"), "https://example.com/v1"))
            .collect();
        assert!(settings(many).normalized().is_err());
        let dangling = AiSettings {
            default_model: Some(AiModelRef {
                connection_id: id(),
                model_id: "m".into(),
                name: "m".into(),
                context_length: None,
                output_length: None,
            }),
            ..AiSettings::default()
        };
        assert_eq!(
            dangling.normalized().unwrap_err().field.as_deref(),
            Some("ai.defaultModel")
        );
    }

    #[test]
    fn repair_keeps_the_usable_parts_of_a_damaged_section() {
        let good = serde_json::to_value(connection(&id(), "A", "https://example.com/v1")).unwrap();
        let mut value = serde_json::json!({
            "connections": [good, {"id": 3}, "x", {"id": "a"}],
            "defaultModel": {"connectionId": 5},
            "route": {"kind": "weird"},
            "extra": 1,
        });
        repair_ai(&mut value);
        let settings: AiSettings = serde_json::from_value(value).unwrap();
        assert_eq!(settings.connections.len(), 1);
        assert_eq!(settings.default_model, None);
        assert_eq!(settings.route, ServiceRoute::Direct);

        let mut value = serde_json::json!({"connections": "nope"});
        repair_ai(&mut value);
        assert!(
            serde_json::from_value::<AiSettings>(value)
                .unwrap()
                .connections
                .is_empty()
        );
    }
}
