//! Global email signature types and limits.
use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// Maximum UTF-8 bytes of a signature's display name.
pub const MAX_SIGNATURE_NAME_BYTES: usize = 120;
/// Maximum UTF-8 bytes of a signature's HTML body.
pub const MAX_SIGNATURE_HTML_BYTES: usize = 256 * 1024;
/// Maximum number of inline images in a single signature.
pub const MAX_SIGNATURE_IMAGES: usize = 10;
/// Maximum total bytes of inline images in a single signature (5 MiB).
pub const MAX_SIGNATURE_IMAGE_BYTES: u64 = 5 * 1024 * 1024;
/// Maximum number of saved global signatures.
pub const MAX_SIGNATURES: usize = 50;

/// Metadata for an inline image belonging to a signature.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct SignatureImage {
    pub id: String,
    pub file_name: String,
    pub media_type: String,
    #[ts(type = "number")]
    pub size: u64,
    pub content_id: String,
}

/// An inline image validated and written to the blob store before the
/// signature itself is saved.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct StagedSignatureImage {
    pub id: String,
    pub file_name: String,
    pub media_type: String,
    #[ts(type = "number")]
    pub size: u64,
    pub content_id: String,
    pub blob_hash: String,
}

/// A saved global email signature.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct Signature {
    pub id: String,
    pub name: String,
    /// Sanitized composer-whitelist HTML fragment.
    pub body_html: String,
    /// Read-only plain-text projection generated by the core.
    pub body_text: String,
    pub images: Vec<SignatureImage>,
    /// Whether this signature is the global default for accounts set to follow default.
    pub is_default: bool,
    pub created_at: String,
    pub updated_at: String,
}

/// How an account selects its signature when composing.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "mode", rename_all = "camelCase")]
pub enum AccountSignatureMode {
    /// Use whichever signature is currently marked as the global default (or none).
    #[default]
    FollowDefault,
    /// Explicitly use no signature for this account.
    None,
    /// Always use this specific signature.
    Specific {
        #[serde(rename = "signatureId")]
        signature_id: String,
    },
}

/// Per-account signature preference (only non-default overrides are stored;
/// omitted accounts implicitly follow the global default signature).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct AccountSignatureDefault {
    pub account_id: String,
    pub selection: AccountSignatureMode,
}

/// Complete signature configuration for settings and composer menus.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
pub struct SignaturesState {
    pub signatures: Vec<Signature>,
    pub account_defaults: Vec<AccountSignatureDefault>,
}

/// Creates a new signature (when `id` is `None`) or updates an existing one.
#[derive(Clone, Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SaveSignatureRequest {
    pub id: Option<String>,
    pub name: String,
    pub body_html: String,
    #[serde(default)]
    pub staged_images: Vec<StagedSignatureImage>,
}

/// Sets an account's signature preference (`followDefault`, `none`, or `specific`).
#[derive(Clone, Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SetAccountSignatureRequest {
    pub account_id: String,
    pub selection: AccountSignatureMode,
}

/// Sets or clears the global default signature (`null` clears the default).
#[derive(Clone, Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SetDefaultSignatureRequest {
    pub signature_id: Option<String>,
}

/// Applies or removes a signature on an existing draft.
#[derive(Clone, Debug, Deserialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct ApplyDraftSignatureRequest {
    pub draft_id: String,
    #[ts(type = "number")]
    pub expected_revision: u32,
    /// `null` removes the signature block from the draft.
    pub signature_id: Option<String>,
}

/// How a newly created draft should select its initial signature.
#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize, TS)]
#[serde(tag = "mode", rename_all = "camelCase")]
pub enum DraftSignatureSelection {
    /// Apply the sending account's configured default signature (if any).
    #[default]
    Default,
    /// Do not insert any signature.
    None,
    /// Apply a specific saved signature by id.
    Specific {
        #[serde(rename = "signatureId")]
        signature_id: String,
    },
}
